// C4 — Part 1: Switch debugging
const status = "open";

switch (status) {
  case "open":
    console.log("Open");
    break;

  default:
    console.log("Unknown status");
}

// C4 — Part 2: Array iteration
const tasks = ["Read", "Review", "Submit"];

for (const task of tasks) {
  console.log(task);
}
